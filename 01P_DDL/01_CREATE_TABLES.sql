CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    USER_NAME VARCHAR2(100),
    EMAIL VARCHAR2(150) UNIQUE,
    PHONE VARCHAR2(15) UNIQUE
);
CREATE TABLE MOVIES (
    MOVIE_ID NUMBER PRIMARY KEY,
    MOVIE_NAME VARCHAR2(150) NOT NULL,
    GENRE VARCHAR2(50),
    LANGUAGE VARCHAR2(30),
    DURATION NUMBER(3),
    RELEASE_DATE DATE
);
CREATE TABLE THEATRES (
    THEATRE_ID NUMBER PRIMARY KEY,
    THEATRE_NAME VARCHAR2(100) NOT NULL,
    CITY VARCHAR2(50) NOT NULL
);
CREATE TABLE SHOWS (
    SHOW_ID NUMBER NOT NULL,
    MOVIE_ID NUMBER NOT NULL,
    THEATRE_ID NUMBER NOT NULL,
    SHOW_DATE DATE NOT NULL,
    SHOW_TIME VARCHAR2(20) NOT NULL,
    TICKET_PRICE NUMBER(8,2) NOT NULL
);
DESC SHOWS;
CREATE TABLE SEATS (
    SEAT_ID NUMBER PRIMARY KEY,
    THEATRE_ID NUMBER NOT NULL,
    SEAT_NUMBER VARCHAR2(10) NOT NULL,
    SEAT_TYPE VARCHAR2(20),
    SEAT_PRICE NUMBER(8,2) NOT NULL
);
CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    SHOW_ID NUMBER NOT NULL,
    BOOKING_DATE DATE NOT NULL,
    TOTAL_AMOUNT NUMBER(10,2) NOT NULL,
    BOOKING_STATUS VARCHAR2(20) NOT NULL
);
CREATE TABLE BOOKING_SEATS (
    BOOKING_SEAT_ID NUMBER PRIMARY KEY,
    BOOKING_ID NUMBER NOT NULL,
    SEAT_ID NUMBER NOT NULL,
    SHOW_ID NUMBER NOT NULL,
    SEAT_PRICE NUMBER(8,2) NOT NULL
);
CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER PRIMARY KEY,
    BOOKING_ID NUMBER NOT NULL,
    PAYMENT_DATE DATE NOT NULL,
    PAYMENT_METHOD VARCHAR2(30) NOT NULL,
    PAYMENT_AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_STATUS VARCHAR2(20) NOT NULL
);
COMMIT;



